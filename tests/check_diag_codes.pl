#!/usr/bin/perl
# check_diag_codes.pl - the message codes of karicheck (dns_diag_codes.h): the table, the docs list generated from it, and the list of codes.
#
#   check_diag_codes.pl --check-table          the table follows the rules: one entry per line, ID = the name in capitals ('.' and '-' as
#                                              '_'), names unique and in a known area, a severity of E W N I, a description
#   check_diag_codes.pl --list                 the names of the codes that are not retired, one per line
#   check_diag_codes.pl --print-docs           the list as Markdown, the text that docs/karicheck.md holds between its two markers
#   check_diag_codes.pl --check-docs [FILE]    the part of docs/karicheck.md between the markers equals --print-docs (exit 1 and a diff
#                                              hint when not: regenerate with --print-docs)
#   check_diag_codes.pl --update-docs [FILE]   write the generated list into the docs between the markers
use strict;
use warnings;

my $root = $0;
$root =~ s{/[^/]*$}{} or $root = '.';
$root .= '/..';
my $table = $ENV{KC_CODES_H} || "$root/dns_diag_codes.h";
my $BEGIN = '<!-- BEGIN CODES (generated by tests/check_diag_codes.pl --print-docs; do not edit) -->';
my $END = '<!-- END CODES -->';
my @AREAS = qw(usage io conf zone db internal);
my %SEV = (E => 'error', W => 'warning', N => 'note', I => 'info');

sub read_table {
    open my $in, '<', $table or die "cannot read $table: $!\n";
    my @codes;
    my $line = 0;
    while (<$in>) {
        $line++;
        s/\r?\n$//;
        next unless /^\s*(XR?)\s*\(/;
        if (!/^(XR?)\s*\((\w+), "([^"]+)", '([EWNI])', "(.*)"\)$/) { push @codes, { error => "line $line: not in the form X (ID, \"name\", 'S', \"description\")" }; next; }
        push @codes, { retired => ($1 eq 'XR'), id => $2, name => $3, sev => $4, desc => $5, line => $line };
    }
    close $in;
    return @codes;
}

sub check_table {
    my @codes = read_table();
    my @err;
    my (%ids, %names);
    for my $c (@codes) {
        if ($c->{error}) { push @err, $c->{error}; next; }
        my $at = "line $c->{line} ($c->{name})";
        (my $want = uc $c->{name}) =~ tr/.-/__/;
        push @err, "$at: the ID is $c->{id}, it must be $want" if $c->{id} ne $want;
        push @err, "$at: ID used twice" if $ids{ $c->{id} }++;
        push @err, "$at: name used twice" if $names{ $c->{name} }++;
        my $areas = join '|', @AREAS;
        push @err, "$at: not '<area>.<subject>[.<detail>]' in lowercase, with area $areas" unless $c->{name} =~ /^(?:$areas)(?:\.[a-z0-9]+(?:-[a-z0-9]+)*)+$/;
        push @err, "$at: empty description" unless length $c->{desc};
        push @err, "$at: the description is longer than 160 characters" if length $c->{desc} > 160;
        push @err, "$at: a quote in the description" if $c->{desc} =~ /(?<!\\)"/;
    }
    push @err, "no codes found in $table" unless @codes;
    if (@err) { print STDERR "$_\n" for @err; return 1; }
    return 0;
}

sub docs_text {
    my @codes = grep { !$_->{error} } read_table();
    my $out = "| Code | Severity | Meaning |\n|---|---|---|\n";
    for my $c (@codes) {
        my $d = $c->{desc};
        $d =~ s/\|/\\|/g;
        $out .= sprintf("| `%s` | %s | %s%s |\n", $c->{name}, $SEV{ $c->{sev} }, $d, $c->{retired} ? ' (retired: no longer printed)' : '');
    }
    return $out;
}

sub read_docs {
    my ($f) = @_;
    open my $in, '<:raw', $f or die "cannot read $f: $!\n";
    local $/;
    my $t = <$in>;
    close $in;
    $t =~ s/\r\n/\n/g;
    return $t;
}

my ($mode, $docs) = @ARGV;
$docs ||= "$root/docs/karicheck.md";
if (!defined $mode) { print STDERR "usage: check_diag_codes.pl --check-table|--list|--print-docs|--check-docs [FILE]|--update-docs [FILE]\n"; exit 2; }
if ($mode eq '--check-table') { exit check_table(); }
elsif ($mode eq '--list') { print "$_->{name}\n" for grep { !$_->{error} && !$_->{retired} } read_table(); exit 0; }
elsif ($mode eq '--print-docs') { print docs_text(); exit 0; }
elsif ($mode eq '--check-docs' || $mode eq '--update-docs') {
    my $t = read_docs($docs);
    my ($b, $e) = (index($t, $BEGIN), index($t, $END));
    if ($b < 0 || $e < $b) { print STDERR "$docs has no \"$BEGIN\" ... \"$END\" block\n"; exit 1; }
    my $have = substr($t, $b + length($BEGIN), $e - $b - length($BEGIN));
    my $want = "\n\n" . docs_text() . "\n";
    if ($mode eq '--check-docs') {
        if ($have ne $want) { print STDERR "the code list in $docs is not the one generated from dns_diag_codes.h; run: perl tests/check_diag_codes.pl --update-docs\n"; exit 1; }
        exit 0;
    }
    substr($t, $b + length($BEGIN), $e - $b - length($BEGIN)) = $want;
    open my $o, '>:raw', $docs or die "cannot write $docs: $!\n";
    print $o $t;
    close $o;
    exit 0;
}
print STDERR "unknown option $mode\n";
exit 2;
